"""Who is allowed into the control room.

The coordinator surfaces hold the things we promised to protect: reporter
names and numbers, exact locations, who is on duty and where. AGENTS.md 9
says contact details are released once, to the volunteer who accepts. None of
that survives if ``/api/cases`` answers anyone who asks.

So the check lives here, on the server, and the UI only reflects it. A
password gate written in React stops nobody: the API is reachable with curl
whether or not the page agrees to render.

Three deliberate choices:

* **The password is never stored, anywhere.** Config carries a PBKDF2 hash,
  generated by ``scripts/hash_password.py``. The repository is public
  (AGENTS.md 12), and a plaintext password in a committed file is the same
  class of mistake as a real phone number.
* **Sessions are signed, not stored.** A token is ``email|expiry|signature``
  with the signature over the first two using ``SESSION_SECRET``. No table, no
  lookup, and nothing to clean up. The cost is that signing out cannot revoke
  a token early -- acceptable for a prototype with one account, and stated in
  the README rather than hidden.
* **Comparisons are constant-time.** ``hmac.compare_digest`` everywhere, so a
  wrong password cannot be narrowed down by timing the response.

Everything here is standard library. No new dependency for a login box.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import logging
import time
from typing import Optional, Tuple

from core import config

logger = logging.getLogger("safezone.auth")

# PBKDF2-HMAC-SHA256. 600k iterations is the OWASP figure for SHA-256 and
# costs a few hundred milliseconds once, at login, which nobody notices.
HASH_NAME = "sha256"
ITERATIONS = 600_000
SALT_BYTES = 16

SESSION_COOKIE = "safezone_session"


class AuthError(Exception):
    """Login failed, or a session is not usable. The message is for logs."""


# ─── Passwords ─────────────────────────────────────────────────────────────


def hash_password(password: str, *, salt: Optional[bytes] = None) -> str:
    """Hash a password into the string that belongs in ADMIN_PASSWORD_HASH.

    Format: ``pbkdf2_sha256$<iterations>$<salt_b64>$<hash_b64>``. Self
    describing, so the iteration count can be raised later without stranding
    hashes made today.
    """
    if not password:
        raise AuthError("Password must not be empty.")

    salt = salt or _random_bytes(SALT_BYTES)
    digest = hashlib.pbkdf2_hmac(HASH_NAME, password.encode("utf-8"), salt, ITERATIONS)
    return "$".join(
        ["pbkdf2_sha256", str(ITERATIONS), _b64(salt), _b64(digest)]
    )


def verify_password(password: str, stored: str) -> bool:
    """Check a password against a stored hash. False on anything malformed."""
    if not password or not stored:
        return False

    try:
        algorithm, iterations, salt_b64, expected_b64 = stored.split("$")
    except ValueError:
        logger.error("ADMIN_PASSWORD_HASH is malformed. Re-run scripts/hash_password.py.")
        return False

    if algorithm != "pbkdf2_sha256":
        logger.error("ADMIN_PASSWORD_HASH uses unknown algorithm %r.", algorithm)
        return False

    try:
        salt = _unb64(salt_b64)
        expected = _unb64(expected_b64)
        rounds = int(iterations)
    except (ValueError, TypeError):
        logger.error("ADMIN_PASSWORD_HASH is malformed. Re-run scripts/hash_password.py.")
        return False

    candidate = hashlib.pbkdf2_hmac(HASH_NAME, password.encode("utf-8"), salt, rounds)
    return hmac.compare_digest(candidate, expected)


# ─── Sessions ──────────────────────────────────────────────────────────────


def issue_session(email: str, *, ttl_hours: Optional[int] = None) -> Tuple[str, int]:
    """Mint a signed session token. Returns ``(token, max_age_seconds)``."""
    secret = _secret()
    hours = ttl_hours if ttl_hours is not None else config.SESSION_TTL_HOURS
    max_age = max(1, int(hours)) * 3600
    expires = int(time.time()) + max_age

    payload = f"{email}|{expires}"
    signature = hmac.new(secret, payload.encode("utf-8"), hashlib.sha256).digest()
    return f"{payload}|{_b64(signature)}", max_age


def read_session(token: Optional[str]) -> Optional[str]:
    """Return the email a token vouches for, or None if it does not.

    None covers every failure the same way -- missing, malformed, tampered
    with, expired -- because the caller's response is identical in each case
    and distinguishing them only helps someone probing.
    """
    if not token:
        return None

    try:
        email, expires_raw, signature_b64 = token.rsplit("|", 2)
        expires = int(expires_raw)
        signature = _unb64(signature_b64)
    except (ValueError, TypeError):
        return None

    expected = hmac.new(
        _secret(), f"{email}|{expires}".encode("utf-8"), hashlib.sha256
    ).digest()
    if not hmac.compare_digest(signature, expected):
        return None

    if expires < time.time():
        return None

    # A session signed for an account that has since been changed in the
    # environment must not keep working.
    if email.lower() != config.ADMIN_EMAIL.strip().lower():
        return None

    return email


def authenticate(email: str, password: str) -> str:
    """Check a login. Returns the canonical email, or raises AuthError.

    The error text is the same for an unknown email and a wrong password: a
    login form that distinguishes them tells an attacker which half to keep.
    """
    if not is_configured():
        raise AuthError(
            "Admin login is not configured on this server. Set ADMIN_EMAIL, "
            "ADMIN_PASSWORD_HASH and SESSION_SECRET."
        )

    given = (email or "").strip().lower()
    expected_email = config.ADMIN_EMAIL.strip().lower()

    email_ok = hmac.compare_digest(given, expected_email)
    password_ok = verify_password(password or "", config.ADMIN_PASSWORD_HASH)

    # Both are evaluated before branching, so the response time does not
    # reveal that the email alone was wrong.
    if not (email_ok and password_ok):
        raise AuthError("Email or password is incorrect.")

    return expected_email


def is_configured() -> bool:
    """Whether this server can authenticate anyone at all."""
    return bool(
        config.ADMIN_EMAIL.strip()
        and config.ADMIN_PASSWORD_HASH.strip()
        and config.SESSION_SECRET.strip()
    )


# ─── Helpers ───────────────────────────────────────────────────────────────


def _secret() -> bytes:
    secret = config.SESSION_SECRET.strip()
    if not secret:
        raise AuthError("SESSION_SECRET is not set.")
    return secret.encode("utf-8")


def _b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")


def _unb64(value: str) -> bytes:
    padding = "=" * (-len(value) % 4)
    return base64.urlsafe_b64decode(value + padding)


def _random_bytes(count: int) -> bytes:
    import secrets

    return secrets.token_bytes(count)
